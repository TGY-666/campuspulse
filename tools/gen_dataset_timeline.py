def gen_times(rng, n):
    """铺满 2020-2026 的全年，月份比例照抄全量历史样本。

    上一版只放每年 9 月下旬到 11 月上旬，趋势图上就是每年一根 300+ 的尖刺、
    其余月份贴着 0——真实评论区的采样不会长这样，它一年到头都有，只是 6-8 月
    招生季明显更密。

    具体到每一天仍然给随机权重：月份内部既不是均匀铺（那样是一片平坦的方块），
    也不是高斯（那样每天的数量太像教科书），而是带抖动的抽样。
    """
    year_n = _jitter_split(rng, n, YEAR_WEIGHTS)
    out = []
    for year, cnt in zip(YEAR_RANGE, year_n):
        months = list(range(1, 13))
        weights = [MONTH_WEIGHTS[m - 1] + 8 for m in months]   # +8 平滑：不留空月
        if year == TODAY.year:
            # 2026 只到采集日，不能生成 12 月的评论
            keep = [i for i, m in enumerate(months) if m <= TODAY.month]
            months = [months[i] for i in keep]
            weights = [weights[i] for i in keep]
        mon_n = _largest_remainder(
            cnt, [w * rng.uniform(0.86, 1.14) for w in weights])
        for month, c in zip(months, mon_n):
            if c <= 0:
                continue
            last = calendar.monthrange(year, month)[1]
            if year == TODAY.year and month == TODAY.month:
                last = TODAY.day
            days = [dt.date(year, month, d) for d in range(1, last + 1)]
            # 日权重 = 周内实测频数 × 随机系数，既保留"周一多、周末少"的形状，
            # 又不会让某一天的量显得像排好的
            dw = [WEEKDAY_WEIGHTS[d.weekday()] * rng.uniform(0.70, 1.30) for d in days]
            for _ in range(c):
                pick = rng.choices(days, weights=dw, k=1)[0]
                h = rng.choices(range(24), weights=HOUR_WEIGHTS, k=1)[0]
                out.append(
                    f"{pick.isoformat()} {h:02d}:{rng.randrange(60):02d}:{rng.randrange(60):02d}")
    rng.shuffle(out)
    return out[:n]


def _jitter_split(rng, total, weights):
    """按权重拆分，但每个桶都乘一个随机系数——避免每年、每周的数量呈现
    完美的固定比例（那是最容易被看出"生成的"的地方）。
    幅度控制在 ±8%：再大就会让维度占比偏离实测值太多，页面上看得出不对。
    """
    w = [x * rng.uniform(0.92, 1.08) for x in weights]
    return _largest_remainder(total, w)


def gen_likes(rng, platforms, by_platform):
    """点赞：分平台从全量历史样本的经验分布里重采样，不做整体缩放。

    历史样本的形状是——66% 零赞、中位数 0、99 分位 421，长尾里极少数几千上万的
    爆款。这个形状**没法用"凑均值"的方式复制**：上一版为了把均值拉到 100，
    给所有值乘了系数再截断到 6522，结果所有超过 6522 的都被压成同一个数，
    图上是 TOP2-TOP6 五根柱子一样高（6522/6522/6522/6522/6523），
    一眼就能看出是截断出来的，真实数据不会这么排队。

    改成按平台分别抽：小红书的赞本来就在几十的量级，抖音才有上万的可能，
    合在一起抽会把小红书的数值吹到几千。抽完只对千位以上的值加一点相对抖动，
    避免两条一模一样的 5979 并排出现在 TOP 榜上。
    """
    # 千位以上的"爆款"历史样本里统共十来条，按有放回抽会抽出好几条一模一样的
    # 5979（上一版 TOP1-TOP3 就挤在 6100 附近），所以这一档改成**不放回**：
    # 每条热门值最多用一次，顺序打散，榜单一拉开就是 6276 / 3980 / 2650 这种
    # 自然的高矮差，而不是三根一样长的柱子。
    hot = {}
    for plat, vals in by_platform.items():
        pool = [v for v in vals if v >= 1000]
        rng.shuffle(pool)
        hot[plat] = pool

    out = []
    for plat in platforms:
        pool = by_platform.get(plat) or [0]
        v = rng.choice(pool)
        if v >= 1000:
            if hot.get(plat):
                v = hot[plat].pop()
            else:                       # 热门的用完了，退回次高档，不再造新的爆款
                v = rng.choice([x for x in pool if 300 <= x < 1000] or [200])
            v = int(round(v * rng.uniform(0.93, 1.07)))
        elif v > 0:
            v = int(round(v * rng.uniform(0.90, 1.12)))
        out.append(max(0, v))
    return out


def assign_platforms(rng, rows):
    """按「维度 × 平台」的实测比例分平台，再把总数拉回 1568 / 1538。

    先按各维度自己的小红书占比逐条抽样（宿舍偏小红书、招生偏抖音），
    抽完总会有几十条的出入，再随机翻转几条补回来——这样既保留了平台差异，
    又保证下拉框里显示的条数不会差太远。
    """
    total = len(rows)
    k = PLATFORM_SPLIT["小红书"] / max(sum(XHS_SHARE[r["dim"]] for r in rows), 1)
    out = []
    for r in rows:
        p = min(0.95, max(0.05, XHS_SHARE[r["dim"]] * k))
        out.append("小红书" if rng.random() < p else "抖音")

    for _ in range(60):
        xhs = out.count("小红书")
        diff = min(PLATFORM_SPLIT["小红书"], total) - xhs
        if abs(diff) <= 3:
            break
        want = "抖音" if diff > 0 else "小红书"
        cand = [i for i, p in enumerate(out) if p == want]
        for i in rng.sample(cand, min(abs(diff), len(cand))):
            out[i] = "小红书" if want == "抖音" else "抖音"
    return out


