# 这条评论还一度被复制成 9 条，留着只会在列表里形成一屏重复。
BAN_WORDS = ("微波炉", "东海岸")


def is_clean_source(text):
    """素材是否可用：不出现校名、不跑题到高中、不是营销留言、不含禁用话题。"""
    if SCHOOL_NAME_RE.search(text):
        return False
    if any(a in text for a in SCHOOL_ABBR):
        return False
    if any(w in text for w in PLACE_WORDS):
        return False
    if any(w in text for w in BAN_WORDS):
        return False
    if OFFTOPIC_RE.search(text) or SPAM_RE.search(text) or TIER_RE.search(text):
        return False
    return True



