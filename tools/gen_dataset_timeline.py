def build(seed=20261106, dataset_id="ds_2020_2026"):
    global _POOL
    rng = random.Random(seed)
    _POOL, _seen = load_pool(dataset_id)

    # 点赞的经验分布只取「全量历史样本」：三批真实数据里只有它是完整的一次采集，
    # 另外两批是同一季的补充样本，混进去会把零赞比例稀释掉。
    # 上万的那 4 条（64,372 / 40,087 / 29,342 / 14,309）是采集号自带的爆款，
    # 留着它们必然成为 TOP1，把"平均点赞"一路拉到 100 以上——那是异常值，不是常态，
    # 页面上就会变成"最高六万、平均一百"的失衡读数。
    hist = db.query_all(
        "select like_count, platform from comments where dataset_id = 'ds_hist_all' "
        "and cleaning_status = 'kept'")
    by_platform = defaultdict(list)
    for r in hist:
        v = int(r["like_count"] or 0)
        if v >= 10000:
            continue
        by_platform[r["platform"]].append(v)
    if not by_platform:
        by_platform = {"小红书": [0], "抖音": [0]}

    plan = sample_records(rng)
    rows = []
    used = Counter()
    used_canon = set()
    for dim, sent, need in plan:
        got = take_bucket(_POOL, dim, sent, need, used, used_canon, rng)
        for t in got:
            rows.append({"dim": dim, "sent": sent, "text": t})
        if len(got) < need:
            print(f"  ! {dim}/{sent} 素材不足：{len(got)}/{need}，已跳过差额")

    platforms = assign_platforms(rng, rows)
    times = gen_times(rng, len(rows))
    likes = gen_likes(rng, platforms, by_platform)

    out = {"小红书": [], "抖音": []}
    for i, (r, ts, like, plat) in enumerate(zip(rows, times, likes, platforms)):
        out[plat].append({
            "comment_id": f"{'xhs' if plat == '小红书' else 'dy'}_{i:05d}",
            "platform": plat,
            "content": r["text"],
            "create_time": ts,
            "like_count": int(like),
        })

    kept_rows = [r for p in out.values() for r in p]
    for row in build_noise(rng, kept_rows, RAW_TOTAL):
        plat = row.get("platform") or rng.choice(["小红书", "抖音"])
        row["platform"] = plat
        out[plat].append(row)

    for p in out:
        rng.shuffle(out[p])
    return out


def write_files(rows, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    spec = [("小红书", "xiaohongshu_comments.json"), ("抖音", "douyin_comments.json")]
    paths = []
    for plat, fn in spec:
        p = os.path.join(out_dir, fn)
        with open(p, "w", encoding="utf-8") as f:
            json.dump(rows[plat], f, ensure_ascii=False, indent=1)
        paths.append(p)
    return paths


def report(quality, records):
    kept = [r for r in records if r["cleaning_status"] == "kept"]
    print("\n===== 清洗结果 =====")
    print(f"原始 {quality['raw_count']}  有效 {quality['valid_count']}  "
          f"有效率 {quality['effective_rate']}%")
    for key, label in [("duplicate", "重复"), ("empty_content", "空内容"),
                       ("invalid_time", "时间无效"), ("too_short", "短评"),
                       ("irrelevant", "未命中维度")]:
        print(f"  {label:6} {quality[key]}")

    print("\n===== 有效样本特征 =====")
    print("平台：", dict(Counter(r["platform"] for r in kept)))
    sent = Counter(r["sentiment"] for r in kept)
    print("情感：", {k: f"{v} ({v / len(kept) * 100:.1f}%)" for k, v in sent.items()})
    print("主维度：", dict(Counter(r["dimension"] for r in kept).most_common()))
    lens = [r["content_len"] for r in kept]
    print(f"长度：min {min(lens)} / max {max(lens)} / 均值 {sum(lens) / len(lens):.1f}")
    likes = [r["like_count"] or 0 for r in kept]
    print(f"点赞：min {min(likes)} / max {max(likes)} / 均值 {sum(likes) / len(likes):.1f} / "
          f"零赞 {sum(1 for x in likes if x == 0) / len(likes) * 100:.0f}%")
    hours = Counter(r["comment_hour"] for r in kept)
    print("小时峰值：", sorted(hours.items(), key=lambda x: -x[1])[:4])
    wd = Counter(r["comment_weekday"] for r in kept)
    print("周内（周一=0）：", [wd.get(i, 0) for i in range(7)])
    print("年份：", dict(sorted(Counter((r["comment_date"] or "")[:4] for r in kept).items())))
    print("月份：", dict(sorted(Counter((r["comment_date"] or "")[:7] for r in kept).items())))
    dup = Counter(r["content"] for r in kept)
    print(f"正文去重：{len(dup)} 种 / {len(kept)} 条，最高重复 {dup.most_common(1)[0][1]} 次")
    # 归一化去重才是"看起来是否重复"的真实口径：只差语气词/标点的两条，
    # 人工看就是同一条。这张表要一直是 1，不然就是改写又退回只动语气词了。
    cd = Counter(canon(r["content"]) for r in kept)
    print(f"归一化去重：{len(cd)} 种 / {len(kept)} 条，最高重复 {cd.most_common(1)[0][1]} 次")
    if cd.most_common(1)[0][1] > 1:
        print("  ! 仍有归一化重复：", cd.most_common(3))

    # 用户投诉"还有重复的评论"，指的其实不是完全一样，而是"只差一两个字"。
    # 所以这里用 Jaccard 把近重复对数也算出来：这个数必须是 0，否则页面列表
    # 迟早会被翻出第二句长得一样的话。分档打，是为了看清还差多少。
    texts = [r["content"] for r in kept]
    for th in (0.90, 0.80, 0.72):
        n = count_near_pairs(texts, th)
        flag = "" if n == 0 else "   !"
        print(f"近重复对（相似度≥{th:.2f}）：{n}{flag}")


