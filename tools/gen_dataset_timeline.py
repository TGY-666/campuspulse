def load_pool(exclude_dataset):
    """从库里所有已有评论中抽素材：按正文去重后，用**当前**规则重判维度与情感。

    为什么不用库里存着的 dimension/sentiment 字段：词典改过（新增实习就业、
    剔掉泛化词），旧标签和新规则对不上。生成脚本必须和线上判定口径一致，
    否则写进去的 3106 条会被 ETL 重新判成别的分布。

    两条收集口径：
      * 按 canon() 去重（标点/语气词不同的两条本来就算同一条）；
      * 命中多个维度也收，归到 primary_dimension——线上统计用的是 dimension
        这一列（主维度），多标签不会让维度合计虚高。放开这一条，宿舍住宿的
        负面原型从 18 条涨到 30 条，重复率跟着降下来。
    """
    pool = defaultdict(list)
    seen = set()
    seen_canon = set()
    marks = ",".join("?" * len(REAL_DATASETS))
    rows = db.query_all(
        f"select content from comments where dataset_id in ({marks}) and content is not null",
        REAL_DATASETS)
    for r in rows:
        text = clean_text(r["content"] or "")
        if not text or text in seen:
            continue
        seen.add(text)
        # 上限 90 字：历史样本里混着几条两百多字的长文（「宿舍楼白墙规则怪谈」
        # 那种整段小说），一旦被截断 + 变体复制十几遍，词云上就会出现
        # 「白墙」「墙体」「触摸」这种和评论毫无关系的词。这类长文在评论区
        # 本身就是极少数，不取它不影响分布。
        if len(text) < 5 or len(text) > 90:
            continue
        if not is_clean_source(text):
            continue
        dims = taxonomy.matched_dimensions(text)
        if not dims:
            continue
        c = canon(text)
        if c in seen_canon:
            continue
        seen_canon.add(c)
        pool[(taxonomy.primary_dimension(text), etl.judge_sentiment(text))].append(text)

    for dim, buckets in EXTRA_CORPUS.items():
        for sent, texts in buckets.items():
            for t in texts:
                t = clean_text(t)
                if t in seen:
                    continue
                if taxonomy.primary_dimension(t) != dim:
                    continue
                if etl.judge_sentiment(t) != sent:
                    continue
                c = canon(t)
                if c in seen_canon:
                    continue
                seen.add(t)
                seen_canon.add(c)
                pool[(dim, sent)].append(t)

    # 最后一道：素材层自己带的近重复（同一条回答被贴了两次、改两个字再发一遍）
    # 在这里统一清掉。放在最后做，是因为要跨 (维度, 情感) 桶一起比——两条只差
    # 一个字的正文如果落在不同维度里，页面上一样会被认成重复。
    flat = [(cell, t) for cell, texts in pool.items() for t in texts]
    kept = dedupe_near(flat)
    dropped = len(flat) - len(kept)
    pool = defaultdict(list)
    for cell, t in kept:
        pool[cell].append(t)
    if dropped:
        print(f"  素材近重复清理：{len(flat)} → {len(kept)}（合并 {dropped} 条相似正文）")
    return pool, seen


# ============================ 改写 ============================
# 原则没变：只改句式外壳和用词，不动句子的意思。但**改写必须真的改字面**。
#
# 上一版只调句末语气词（呀/哈/了/吧…），于是「还有冰箱微波炉就是住宿费很贵」
# 在库里出现 9 次，9 条正文只差最后一个字；用户搜「微波炉」，一屏全是它。
# 那不是"改写"，是复制粘贴，只是换了个语气词。
#
# 这一版把改写拆成四个改变字面的轴：
#   A 同义替换  食堂→饭堂、感觉→觉得、有点→有些（只换同地区同语境的词）
#   B 虚词删减  去掉"其实/反正/就是/真的"这类可删的虚词
#   C 分句截取  长句取前半句/后半句（都是能独立成句的话）
#   D 分句换序  两个分句调换顺序，信息不变
# 并且全库按 canon() 判重：任两条正文的归一化文本不得相同。
CLAUSE_SPLIT = re.compile(r"[，。！？]")
PUNCT_RE = re.compile(r"[，。！？～~、,.!?…\s\"'“”‘’()（）:：;；]+")
TONE_CHARS = "啊呢吧了呀哈嘛诶哦噢啦嘞呦"
ORAL_PREFIX = ("想问下", "请问", "有没有人知道", "说真的", "个人感觉",
               "顺便说一句", "讲真", "说实话")


def canon(text):
    """归一化文本：抹掉"读起来完全一样"的差异，用来判重。

    抹掉的是：标点、句首口头语（说真的/讲真…）、句末语气词（呀/哈/了…）、
    句尾的"的"。「很贵」和「很贵呀」「很贵。」归一化后相同 —— 它们就是一条
    评论的三个变体，不该同时出现在库里。
    但同义替换（饭堂/食堂）、分句截取、换序**不**归一化：那是两个人的说法。
    """
    s = PUNCT_RE.sub("", text or "")
    changed = True
    while changed:
        changed = False
        for p in ORAL_PREFIX:
            if s.startswith(p):
                s = s[len(p):]
                changed = True
    while s and s[-1] in TONE_CHARS:
        s = s[:-1]
    if s.endswith("的"):
        s = s[:-1]
    return s


# ======================= 素材层的近重复清理 =======================
# 这里处理的是"语料自己就重复"的情况：同一条回答被不同账号贴了两次、同一个人
# 隔天改了两个字再发一遍。它们不是改写造成的，但读者看到的就是同一句话。
# 必须在选材之前掐掉，否则后面无论怎么挑，列表里都躲不开。
#
# 判据用 canon() 之后的二元组 Jaccard 相似度：差一个字的 20 字短句 Jaccard
# 大约 0.85，两段不同的话通常低于 0.3，中间没有模糊地带。
NEAR_DUP_SIM = 0.72
POSTING_CAP = 400          # 「宿舍」这种高频二元组不参与召回，它区分不了任何东西


def _bigrams(norm_text):
    return {norm_text[i:i + 2] for i in range(max(1, len(norm_text) - 1))}


def _jaccard(a, b):
    if not a or not b:
        return 0.0
    return len(a & b) / len(a | b)


def dedupe_near(texts, threshold=NEAR_DUP_SIM):
    """去掉互为近重复的正文，每组只留一条（先长后短：长的那条信息更全）。

    texts 里可以是字符串，也可以是 (cell, text)；返回值保持同样的形状。
    """
    wrapped = isinstance(texts[0], tuple) if texts else False
    items = []
    for it in texts:
        cell, t = it if wrapped else (None, it)
        items.append((cell, t, canon(t)))
    items.sort(key=lambda x: -len(x[2]))

    accepted = []
    index = defaultdict(list)
    for cell, raw, norm in items:
        grams = _bigrams(norm)
        cand = set()
        for g in grams:
            post = index.get(g)
            if post and len(post) <= POSTING_CAP:
                cand.update(post)
        dup = False
        for i in cand:
            other = accepted[i][2]
            # 先在长度上粗筛：差一半长度的两句话不可能"看起来一样"
            if abs(len(other) - len(norm)) > max(6, int(0.35 * len(norm))):
                continue
            if _jaccard(grams, accepted[i][3]) >= threshold:
                dup = True
                break
        if dup:
            continue
        accepted.append((cell, raw, norm, grams))
        for g in grams:
            index[g].append(len(accepted) - 1)

    out = [((c, t) if wrapped else t) for c, t, _, _ in accepted]
    return out


def count_near_pairs(texts, threshold):
    """统计正文里相似度 ≥ threshold 的配对数，用来验收"有没有重复"。

    dedupe_near 是"边收边判"，这里则是事后体检：即使每一步都做了判断，
    也还是要从头数一遍还剩多少对——两个数字对得上，才算真的清干净了。
    """
    items = [(canon(t), _bigrams(canon(t))) for t in texts]
    index = defaultdict(list)
    for i, (_, grams) in enumerate(items):
        for g in grams:
            index[g].append(i)
    seen_pairs = set()
    for g, ids in index.items():
        if len(ids) > POSTING_CAP:
            continue
        for a in range(len(ids)):
            for b in range(a + 1, len(ids)):
                i, j = ids[a], ids[b]
                if i > j:
                    i, j = j, i
                seen_pairs.add((i, j))
    n = 0
    for i, j in seen_pairs:
        if _jaccard(items[i][1], items[j][1]) >= threshold:
            n += 1
    return n


def take_bucket(pool, dim, sent, need, used, used_canon, rng):
    """从一个 (维度, 情感) 桶里取 need 条正文，**每条原文只用一次**。

    上一版允许"换句/换词"造变体，一条原型最多领 4 次，凑出了 3106 条。
    代价是 800 条正文和原句的相似度在 0.85 以上——用户截图投诉的就是这个。
    现在不做任何改写了：素材池里有多少条互不相像的正文，这一版就只有多少条。
    取不满就少几条，由 report 打出缺口，绝不用改写去填。
    """
    texts = pool.get((dim, sent)) or []
    if not texts:
        return []

    picked = []
    order = texts[:]
    rng.shuffle(order)
    for t in order:
        if len(picked) >= need:
            break
        c = canon(t)
        if used[t] or c in used_canon:
            continue
        used[t] += 1
        used_canon.add(c)
        picked.append(t)
    return picked


# ============================ 分布 ============================
def plan_matrix(rng):
    """维度 × 情感的期望条数。

    不做 IPF 精确配平：那样每一格都会被卡成整数，最后看上去像拿尺子量出来的。
    这里只把**整体**的比例校准到目标，每一格再在抽样阶段自然抖动，
    让维度之间、情感之间的比例有高有低——真实样本本来就不会整除。
    """
    dims = list(DIM_SHARE)
    dim_n = {d: VALID_TOTAL * DIM_SHARE[d] for d in dims}

    # 起手比例取自素材池本身：池子里是什么情感构成，就先按什么分。
    # 这样生成出来的分布天然贴近真实样本，只需要把整体校准到目标。
    #
    # 但小维度要往全量比例收缩：校园活动在历史语料里只有 30 条原型，里面恰好
    # 3 条是负面，照池子的比例算，这一维的负面率就是 30%——页面上会变成一根
    # 一半红的短柱，读者只会得出"活动办得最差"的结论，而那只是样本太少。
    # 权重 w = 原型数 / 120，样本越少越靠近全量比例。
    mat = {}
    for d in dims:
        cnt = {s: len(_POOL.get((d, s)) or []) for s in ("positive", "neutral", "negative")}
        tot = sum(cnt.values()) or 1
        w = min(1.0, tot / 120)
        mat[d] = {
            "positive": w * cnt["positive"] / tot + (1 - w) * POS_RATE,
            "negative": w * cnt["negative"] / tot + (1 - w) * NEG_RATE,
        }
        mat[d]["neutral"] = max(0.05, 1 - mat[d]["positive"] - mat[d]["negative"])

    # 把整体正面率/负面率拉到目标：按列做比例校正，迭代到收敛。
    # 上下限是护栏：某一维度的负面率被顶到 45% 以上时，它在页面上会变成
    # 一条刺眼的红柱，而真实样本里没有哪个维度会这样。
    for _ in range(8):
        pos = sum(dim_n[d] * mat[d]["positive"] for d in dims) / VALID_TOTAL
        neg = sum(dim_n[d] * mat[d]["negative"] for d in dims) / VALID_TOTAL
        kp = POS_RATE / pos if pos else 1
        kn = NEG_RATE / neg if neg else 1
        for d in dims:
            p = min(mat[d]["positive"] * kp, 0.62)
            n = min(mat[d]["negative"] * kn, 0.42)
            mat[d] = {"positive": p, "negative": n, "neutral": max(0.05, 1 - p - n)}

    return dim_n, mat


