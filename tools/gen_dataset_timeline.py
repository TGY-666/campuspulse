def sample_records(rng):
    """逐条独立抽样，让最终每一格的条数都带自然抖动。

    只有**整体**正/负条数会被拉回目标：这三个数是页面上直接显示、
    也是需求点名的（26.7% / 7.8%），偏 0.5 个百分点就对不上。
    每一条维度内部的构成仍然随机，所以不会出现"每格都整除"的假感。
    """
    dims = list(DIM_SHARE)
    dim_n, mat = plan_matrix(rng)
    # 维度条数也带抖动，而不是按占比精确切分
    dim_int = _jitter_split(rng, VALID_TOTAL, [dim_n[d] for d in dims])

    cell = {}
    for d, n in zip(dims, dim_int):
        probs = [mat[d]["positive"], mat[d]["neutral"], mat[d]["negative"]]
        counts = _multinomial(rng, n, probs)
        for sent, c in zip(("positive", "neutral", "negative"), counts):
            cell[(d, sent)] = c

    target = {
        "positive": round(VALID_TOTAL * POS_RATE),
        "negative": round(VALID_TOTAL * NEG_RATE),
    }
    target["neutral"] = VALID_TOTAL - target["positive"] - target["negative"]

    for sent in ("positive", "neutral", "negative"):
        pool_dims = [d for d in dims if (d, sent) in cell]
        cur = sum(cell[(d, sent)] for d in pool_dims)
        diff = target[sent] - cur
        # 按当前条数轮转加减：大桶多分担一点，小桶不至于被砍到 0
        order = sorted(pool_dims, key=lambda d: -cell[(d, sent)])
        i, guard = 0, 0
        while diff != 0 and order and guard < 20000:
            guard += 1
            d = order[i % len(order)]
            if diff > 0:
                cell[(d, sent)] += 1
                diff -= 1
            elif cell[(d, sent)] > 1:
                cell[(d, sent)] -= 1
                diff += 1
            i += 1

    return [(d, s, c) for (d, s), c in cell.items() if c > 0]


def _multinomial(rng, n, probs):
    """多项式抽样：等价于把 n 个球逐个按概率扔进 3 个桶。"""
    out = [0, 0, 0]
    p0, p1 = probs[0], probs[0] + probs[1]
    for _ in range(n):
        u = rng.random()
        if u < p0:
            out[0] += 1
        elif u < p1:
            out[1] += 1
        else:
            out[2] += 1
    return out


def _largest_remainder(total, weights):
    s = float(sum(weights)) or 1.0
    raw = [total * w / s for w in weights]
    base = [int(math.floor(x)) for x in raw]
    rest = total - sum(base)
    order = sorted(range(len(raw)), key=lambda i: raw[i] - base[i], reverse=True)
    for i in order[:rest]:
        base[i] += 1
    return base


